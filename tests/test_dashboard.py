"""Smoke test for the Streamlit dashboard (Phase 8).

Loads app/dashboard.py with streamlit.testing.v1.AppTest and confirms it
runs without raising, against the real artifacts generated by earlier
phases (the dashboard reads only precomputed files, never recomputes).
"""

from pathlib import Path

import pytest
from streamlit.testing.v1 import AppTest

REPO_ROOT = Path(__file__).resolve().parents[1]
APP_PATH = REPO_ROOT / "app" / "dashboard.py"
METRICS_DIR = REPO_ROOT / "artifacts" / "metrics"

pytestmark = pytest.mark.skipif(
    not (METRICS_DIR / "tuning_WLT-01.json").exists(),
    reason="requires artifacts/metrics from a prior make tuning/model/papers run",
)


def test_dashboard_loads_without_error():
    at = AppTest.from_file(str(APP_PATH), default_timeout=60)
    at.run()
    assert not at.exception


def test_dashboard_shows_synthetic_data_banner():
    at = AppTest.from_file(str(APP_PATH), default_timeout=60)
    at.run()
    assert not at.exception
    warnings = [w.value for w in at.warning]
    assert any("SYNTHETIC DATA" in w for w in warnings)


def test_whatif_tab_renders_metrics_for_default_scenario():
    at = AppTest.from_file(str(APP_PATH), default_timeout=60)
    at.run()
    assert not at.exception
    # The scenario selectbox defaults to the first scenario; its metrics
    # should render without needing any interaction.
    assert len(at.metric) > 0


def test_alert_queue_tab_has_scenario_filter():
    at = AppTest.from_file(str(APP_PATH), default_timeout=60)
    at.run()
    assert not at.exception
    assert len(at.multiselect) >= 1
    assert at.multiselect[0].value == ["STR-01", "RMV-01", "FAN-01", "FAN-02", "WLT-01"]
